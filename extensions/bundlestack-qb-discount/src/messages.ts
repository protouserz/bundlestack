export function interpolate(
  template: string,
  vars: Record<string, string | number>,
): string {
  let result = template;
  for (const [key, value] of Object.entries(vars)) {
    result = result.split(`{${key}}`).join(String(value));
  }
  return result;
}

export function checkoutMessages(isoCode?: string | null): CheckoutMessages {
  const key = String(isoCode || "EN")
    .replace(/-/g, "_")
    .toUpperCase();
  return BY_LANG[key] ?? BY_LANG[key.split("_")[0] ?? ""] ?? EN;
}
